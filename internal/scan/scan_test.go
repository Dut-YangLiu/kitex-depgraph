func TestParseGoMod(t *testing.T) {
	m, err := parseGoMod([]byte(`module example.com/order-svc // trailing comment

go 1.21

require github.com/cloudwego/kitex v0.8.0

require (
	example.com/idl v1.2.3
	// a comment line
	github.com/Shopify/sarama v1.38.1 // indirect
)

replace example.com/idl => ../idl

replace (
	github.com/apache/thrift => github.com/apache/thrift v0.13.0
	example.com/old v1.0.0 => example.com/new v2.0.0
)
`))
	if err != nil {
		t.Fatal(err)
	}
	if m.Module != "example.com/order-svc" || m.Go != "1.21" {
		t.Fatalf("module/go = %q/%q", m.Module, m.Go)
	}
	wantReq := map[string]string{
		"github.com/cloudwego/kitex": "v0.8.0",
		"example.com/idl":            "v1.2.3",
		"github.com/Shopify/sarama":  "v1.38.1",
	}
	if !reflect.DeepEqual(m.Requires, wantReq) {
		t.Fatalf("requires = %v", m.Requires)
	}
	if len(m.Replaces) != 3 {
		t.Fatalf("replaces = %v", m.Replaces)
	}
	if r := m.Replaces[0]; r.OldPath != "example.com/idl" || r.NewPath != "../idl" || !r.isLocal() {
		t.Errorf("local replace = %+v", r)
	}
	if r := m.Replaces[2]; r.OldVersion != "v1.0.0" || r.NewPath != "example.com/new" || r.NewVersion != "v2.0.0" || r.isLocal() {
		t.Errorf("versioned replace = %+v", r)
	}
	if _, err := parseGoMod([]byte("go 1.21\n")); err == nil {
		t.Error("missing module directive should fail")
	}
}

