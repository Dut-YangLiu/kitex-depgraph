func parsePkg(t *testing.T, path string, srcs ...string) *lpkg {
	t.Helper()
	fset := token.NewFileSet()
	p := &lpkg{importPath: path}
	for i, src := range srcs {
		f, err := parser.ParseFile(fset, "f"+string(rune('0'+i))+".go", src, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		p.files = append(p.files, f)
	}
	p.gen = detectGen(p.files, path, []string{"kitex_gen"})
	return p
}

// Kitex v0.12 layout: package-level serviceMethods, lower-case IDL method.
const v012Service = `// Code generated by Kitex v0.12.0. DO NOT EDIT.

package echo

var serviceMethods = map[string]kitex.MethodInfo{
	"echo": kitex.NewMethodInfo(echoHandler, newArgs, newResult, false),
}

func newServiceInfo(hasStreaming bool) *kitex.ServiceInfo {
	serviceName := "Echo"
	handlerType := (*api.Echo)(nil)
	extra := map[string]interface{}{
		"PackageName": "api",
	}
	return &kitex.ServiceInfo{ServiceName: serviceName, HandlerType: handlerType, PayloadCodec: kitex.Thrift, KiteXGenVersion: "v0.12.0", Extra: extra}
}

func (p *kClient) Echo(ctx context.Context, req *api.Request) (r *api.Response, err error) {
	if err = p.c.Call(ctx, "echo", &_args, &_result); err != nil {
		return
	}
	return
}
`

const v012Client = `// Code generated by Kitex v0.12.0. DO NOT EDIT.

package echo

type Client interface {
	Echo(ctx context.Context, req *api.Request, callOptions ...callopt.Option) (r *api.Response, err error)
}

func NewClient(destService string, opts ...client.Option) (Client, error) { return nil, nil }
`

// Kitex v0.4 layout: methods map inside NewServiceInfo, no ServiceFilePath.
const v043Service = `// Code generated by Kitex v0.4.3. DO NOT EDIT.

package noteservice

func NewServiceInfo() *kitex.ServiceInfo {
	serviceName := "NoteService"
	handlerType := (*demonote.NoteService)(nil)
	methods := map[string]kitex.MethodInfo{
		"CreateNote": kitex.NewMethodInfo(createNoteHandler, a, b, false),
		"MGetNote":   kitex.NewMethodInfo(mGetNoteHandler, a, b, false),
	}
	extra := map[string]interface{}{
		"PackageName": "demonote",
	}
	svcInfo := &kitex.ServiceInfo{ServiceName: serviceName, PayloadCodec: kitex.Thrift, KiteXGenVersion: "v0.4.3", Extra: extra}
	return svcInfo
}

func NewServer(handler demonote.NoteService, opts ...server.Option) server.Server { return nil }
`

func TestExtractServiceV012(t *testing.T) {
	p := parsePkg(t, "github.com/x/kitex_gen/api/echo", v012Service, v012Client)
	if !p.gen.kitex || p.gen.kitexVersion != "v0.12.0" {
		t.Fatalf("gen = %+v", p.gen)
	}
	si := extractService(p)
	if si == nil {
		t.Fatal("not recognised as a service package")
	}
	if si.key != "api.Echo" || si.codec != "Thrift" || si.kitexVersion != "v0.12.0" || si.handlerType != "api.Echo" {
		t.Errorf("service = %+v", si)
	}
	want := []model.Method{{Go: "Echo", Wire: "echo"}}
	if !reflect.DeepEqual(si.methods, want) {
		t.Errorf("methods = %+v, want %+v", si.methods, want)
	}
	if si.wire("Echo") != "echo" {
		t.Errorf("wire(Echo) = %q", si.wire("Echo"))
	}
}

