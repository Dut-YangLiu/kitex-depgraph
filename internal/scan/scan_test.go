func TestClassifyHeader(t *testing.T) {
	cases := []struct {
		text, kind, version string
	}{
		{"// Code generated by Kitex v0.12.0. DO NOT EDIT.\n\npackage echo", genKitex, "v0.12.0"},
		{"// Code generated by Kitex v0.4.3. DO NOT EDIT.\npackage x", genKitex, "v0.4.3"},
		{"// Code generated by thriftgo (0.3.18). DO NOT EDIT.\n\npackage api", genThriftgo, ""},
		{"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb", genOther, ""},
		{"// Copyright 2024\n\npackage main", "", ""},
		{"package main\n// Code generated by Kitex v1.0.0. DO NOT EDIT.", "", ""},
	}
	for _, c := range cases {
		kind, ver := classifyHeader(c.text)
		if kind != c.kind || ver != c.version {
			t.Errorf("classifyHeader(%q) = %q,%q want %q,%q", c.text, kind, ver, c.kind, c.version)
		}
	}
}

